#!/usr/bin/env python3
"""Render docs/CLAIMS.md from the claims registry, or check that it is current.

    python scripts/claims.py            write docs/CLAIMS.md (same as: render)
    python scripts/claims.py render     write docs/CLAIMS.md
    python scripts/claims.py --check    exit 1 if docs/CLAIMS.md is not what render would write

The registry is src/irondome/claims.json. The document is generated, never
edited by hand: tests/claims/test_registry.py fails when the two disagree.
Standard library only; runs on every Python IronDome supports.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

REPOSITORY = Path(__file__).resolve().parent.parent
REGISTRY = REPOSITORY / "src" / "irondome" / "claims.json"
DOCUMENT = REPOSITORY / "docs" / "CLAIMS.md"

_PLATFORMS = {"macos": "macOS", "linux": "Linux", "windows": "Windows"}


def load(path: Path = REGISTRY) -> Dict[str, Any]:
    with open(path, encoding="utf-8") as handle:
        document = json.load(handle)
    if not isinstance(document, dict) or not isinstance(document.get("claims"), list):
        raise SystemExit(f"{path} is not a claims registry")
    return document


def _test_link(node_id: str) -> str:
    """A node id as a link relative to docs/, pointing at its file."""
    path = node_id.split("::", 1)[0]
    return f"[`{node_id}`](../{path})"


def _closers(registry: Dict[str, Any], limit: str) -> List[str]:
    return [claim["id"] for claim in registry["claims"] if limit in claim.get("closes", [])]


def render(registry: Dict[str, Any]) -> str:
    """The text of docs/CLAIMS.md for *registry*. Deterministic: the same registry gives the same bytes."""
    claims = registry["claims"]
    lines: List[str] = [
        "# Claims",
        "",
        "<!-- Generated by scripts/claims.py from src/irondome/claims.json. Do not edit by hand. -->",
        "",
        registry.get("about", "").strip(),
        "",
        "Run the checks on your own machine with `irondome verify` (`irondome verify --claim ID` for one claim,",
        "`irondome verify --touch` to add the one check that needs your finger). Run the tests with `pytest`;",
        "`scripts/test-linux.sh` runs them again on Linux against a software TPM.",
        "",
        "| Claim | Promise | Platforms | Tests | On your machine |",
        "| --- | --- | --- | --- | --- |",
    ]
    for claim in claims:
        platforms = ", ".join(_PLATFORMS.get(name, name) for name in claim["platforms"])
        check = f"`{claim['selfcheck']}`" if claim.get("selfcheck") else "test suite only"
        lines.append(
            f"| [`{claim['id']}`](#{claim['id']}) | {claim['title']} | {platforms} | {len(claim['tests'])} | {check} |"
        )
    limits = registry.get("closed_limits", {})
    if limits:
        lines += ["", "## Limits of IronDome 3.x that version 4 closes", "", "| Limit | In 3.x | Closed by |",
                  "| --- | --- | --- |"]
        for key, text in limits.items():
            closers = ", ".join(f"[`{claim}`](#{claim})" for claim in _closers(registry, key)) or "nothing yet"
            lines.append(f"| {key} | {text} | {closers} |")
    for claim in claims:
        lines += ["", f"## {claim['id']}", "", f"**{claim['title']}**", "", claim["statement"], ""]
        lines += [f"*Where it stops:* {claim['boundary']}", ""]
        platforms = ", ".join(_PLATFORMS.get(name, name) for name in claim["platforms"])
        lines.append(f"- Platforms: {platforms}")
        for key in claim.get("closes", []):
            lines.append(f"- Closes {key}: {limits.get(key, key)}")
        if claim.get("selfcheck"):
            lines.append(
                f"- On your machine: `irondome verify --claim {claim['id']}` (check `{claim['selfcheck']}`)"
            )
        else:
            lines.append("- On your machine: no check of its own; the test suite covers it")
        lines += ["", f"Tests ({len(claim['tests'])}):", ""]
        lines += [f"- {_test_link(node_id)}" for node_id in claim["tests"]] or ["- none yet"]
    return "\n".join(lines) + "\n"


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(prog="scripts/claims.py", description="Render docs/CLAIMS.md from the registry.")
    parser.add_argument("action", nargs="?", choices=["render"], default="render", help="write docs/CLAIMS.md")
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/CLAIMS.md is stale; write nothing")
    args = parser.parse_args(argv)
    text = render(load())
    if args.check:
        current = DOCUMENT.read_text(encoding="utf-8") if DOCUMENT.exists() else ""
        if current != text:
            print("docs/CLAIMS.md is out of date: run python scripts/claims.py render", file=sys.stderr)
            return 1
        return 0
    DOCUMENT.parent.mkdir(parents=True, exist_ok=True)
    DOCUMENT.write_text(text, encoding="utf-8")
    print(f"wrote {DOCUMENT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
